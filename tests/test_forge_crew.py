def test_an_installed_skill_becomes_a_pull_request_with_you_as_co_author(tmp_path, monkeypatch):
    from core import github_pr
    d = tmp_path / "moon_phase"
    d.mkdir()
    (d / "SKILL.md").write_text("---\nname: moon_phase\n---\n", encoding="utf-8")
    (d / "tools.py").write_text("x = 1\n", encoding="utf-8")
    (d / "notes.bin").write_bytes(b"\0")
    http = FakeHTTP()
    gh = github_pr.GitHub("o/r", "t", http=http)
    pr = github_pr.propose_skill("moon_phase", d, "Moon phases.", "tell me the moon phase",
                                 [{"msg": "facts checked: 1 against sources"}], gh=gh)
    assert pr == {"url": "https://github.com/o/r/pull/7", "number": 7}
    commit = next(j for m, p, j in http.calls if p == "/repos/o/r/git/commits" and m == "POST")
    assert commit["message"].endswith("Co-authored-by: Ionuț <42+IonutBotoroga230036@users.noreply.github.com>")
    assert commit["parents"] == ["base"] and commit["author"]["name"] == "E.V.A."
    tree = next(j for m, p, j in http.calls if p == "/repos/o/r/git/trees")
    assert [t["path"] for t in tree["tree"]] == ["skills/moon_phase/SKILL.md", "skills/moon_phase/tools.py"]
    pull = next(j for m, p, j in http.calls if p == "/repos/o/r/pulls")
    assert pull["base"] == "main" and pull["head"].startswith("eva/skill-moon-phase-") and "facts checked" in pull["body"]


