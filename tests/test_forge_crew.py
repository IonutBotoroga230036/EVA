class FactsClaude:
    def __init__(self, reply):
        self.reply, self.asked = reply, []

    def message(self, **kw):
        self.asked.append(kw)
        return {"text": self.reply, "cost_eur": 0.03, "searches": 2}


def test_a_wrong_fact_in_a_test_is_corrected_before_coding():
    from core import forge_facts
    plan = {"method": "offline formula", "test_cases": [
        {"tool": "moon_phase", "args": {"date": "2026-11-24"}, "expect": "full moon"},
        {"tool": "moon_phase", "args": {"date": "nonsense"}, "expect": "an error"}]}
    claude = FactsClaude('I searched.\n```json\n{"checks": [{"index": 0, "factual": true, "correct": false, '
                         '"fixed_expect": "first quarter", "source": "https://www.timeanddate.com/moon/phases/"}, '
                         '{"index": 1, "factual": false}]}\n```')
    fixed, notes, cost = forge_facts.check(plan, "tell me the moon phase", client=claude)
    assert fixed["test_cases"][0]["expect"] == "first quarter" and fixed["test_cases"][1]["expect"] == "an error"
    assert cost == 0.03 and claude.asked[0]["tools"] == [forge_facts.WEB_SEARCH]
    assert notes[0]["msg"].startswith("fact check corrected a test: moon_phase expected 'full moon'")
    assert notes[-1]["msg"].startswith("facts checked: 1 against sources, 1 corrected (https://www.timeanddate.com")


