MOON = '''import json
from datetime import datetime, timezone

NEW = datetime(2000, 1, 6, 18, 14, tzinfo=timezone.utc)
SYN = 29.530588853
NAMES = ["new moon", "waxing crescent", "first quarter", "waxing gibbous", "full moon",
         "waning gibbous", "last quarter", "waning crescent"]


def moon_phase(date: str = "", **_):
    try:
        d = datetime.fromisoformat(date).replace(tzinfo=timezone.utc) if date else datetime.now(timezone.utc)
    except ValueError:
        return {"result": json.dumps({"error": "bad date"}), "say": "I need a date like 2026-10-01, sir."}
    age = ((d - NEW).total_seconds() / 86400) % SYN
    name = NAMES[int((age / SYN) * 8 + 0.5) % 8]
    return {"result": json.dumps({"phase": name, "age_days": round(age, 1)}), "say": f"It's a {name}, sir."}
'''

TESTS = '''import json
import tools


def test_new_moon_at_the_epoch():
    out = tools.moon_phase(date="2000-01-06T18:14:00")
    assert json.loads(out["result"])["phase"] == "new moon" and out["say"]


def test_bad_date_is_an_error_not_a_crash():
    out = tools.moon_phase(date="not a date")
    assert "error" in json.loads(out["result"])
'''

PLAN = {"feasible": True, "name": "moon_phase", "description": "Tells the moon phase for a date.",
        "summary_for_user": "It tells you the moon phase, offline.", "method": "offline formula",
        "network_hosts": [], "tools": [{"name": "moon_phase", "description": "The moon phase for a date (YYYY-MM-DD).",
                                        "params": {"date": "string"}, "changes_something": False,
                                        "trigger_words": ["moon", "phase", "lunar"]}],
        "test_cases": [{"tool": "moon_phase", "args": {"date": "2000-01-06T18:14:00"}, "expect": "new moon"}]}


class FakeBrain:
    def __init__(self, plan=PLAN, coder=None, tester=None, fixer=None, review=None, mode="local", delay=0.0):
        self.plan, self.mode, self.delay = plan, mode, delay
        self.coder = list(coder or [f"```python\n{MOON}```"])
        self.tester = tester or f"```python\n{TESTS}```"
        self.fixer = list(fixer or [])
        self.review = review or {"safe": True, "matches_request": True, "concerns": []}
        self.calls = []

    def pick(self, feature=None):
        return self.mode

    def code_json(self, system, messages, tool):
        role = re.match(r"ROLE: (\w+)", system).group(1)
        self.calls.append(role)
        return (self.plan if role == "planner" else self.review), 0.0, "fake"

    def code_text(self, system, messages):
        role = re.match(r"ROLE: (\w+)", system).group(1)
        self.calls.append(role)
        time.sleep(self.delay)
        if role == "coder":
            return self.coder.pop(0), 0.0, "fake"
        if role == "tester":
            return self.tester, 0.0, "fake"
        return self.fixer.pop(0), 0.0, "fake"


@pytest.fixture
def forge(tmp_path):
    f = Forge(skills_dir=tmp_path / "skills", brain=None)
    f._state = tmp_path / "proposals.json"
    return f


def build(forge, brain, request="tell me the moon phase", stages=None):
    return fc.Crew(brain, forge, progress=(stages.append if stages is not None else None)).build(request)


def test_the_moon_phase_builds_and_passes_its_independent_tests(forge):
    stages = []
    p = build(forge, FakeBrain(), stages=stages)
    assert p.status == "ready", p.reason
    assert p.tests_passed == 2 and p.tools == ["moon_phase"] and p.network_hosts == []
    assert stages == ["planning", "coding and writing tests", "reviewing"]
    tools_py = (forge.quarantine / "moon_phase" / "tools.py").read_text(encoding="utf-8")
    assert "generated by FORGE from the plan (not by a model)" in tools_py
    assert "trusted: false" in (forge.quarantine / "moon_phase" / "SKILL.md").read_text(encoding="utf-8")


def test_the_log_case_a_wrong_function_name_is_fixed_by_the_fixer(forge):
    wrong = "```python\n" + MOON.replace("def moon_phase(", "def moonphase(") + "```"
    brain = FakeBrain(coder=[wrong], fixer=[f"```python\n{MOON}```"])
    stages = []
    p = build(forge, brain, stages=stages)
    assert p.status == "ready", p.reason
    assert brain.calls == ["planner", "coder", "tester", "fixer", "reviewer"]
    assert "fixing, round 1 of 4" in stages


def test_a_failing_test_goes_back_with_the_real_error(forge):
    broken = "```python\n" + MOON.replace('NAMES[int((age / SYN) * 8 + 0.5) % 8]', '"full moon"') + "```"
    brain = FakeBrain(coder=[broken], fixer=[f"```python\n{MOON}```"])
    p = build(forge, brain)
    assert p.status == "ready"


def test_gives_up_honestly_after_the_last_round(forge):
    broken = "```python\ndef moonphase(**_):\n    return {}\n```"
    p = build(forge, FakeBrain(coder=[broken], fixer=[broken] * 4))
    assert p.status == "rejected" and "moon_phase is missing" in p.reason


def test_only_the_planner_can_say_cant_be_done(forge):
    p = build(forge, FakeBrain(plan={"feasible": False, "reason": "needs a paid API key"}))
    assert p.status == "infeasible" and p.reason == "needs a paid API key"


