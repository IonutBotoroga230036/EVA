def test_crew_can_be_switched_off(tmp_path, monkeypatch):
    import core.settings as st
    local = tmp_path / "settings.local.yaml"
    local.write_text("forge:\n  crew: false\n", encoding="utf-8")
    monkeypatch.setattr(st, "LOCAL_PATH", local)
    st.get_settings.cache_clear()
    assert not Forge(skills_dir=tmp_path / "s", brain=FakeBrain())._use_crew()


def test_brain_code_text_yields_like_the_json_path(monkeypatch):
    import httpx
    from core import activity
    from core.brain import Brain
    b = Brain(claude=None)
    monkeypatch.setattr(b, "pick", lambda *a, **k: "local")
    lines = [json.dumps({"message": {"content": "```python\nx = 1\n```"}, "done": False}),
             json.dumps({"message": {"content": ""}, "done": True})]
    b.http = httpx.Client(transport=httpx.MockTransport(lambda r: httpx.Response(200, text="\n".join(lines))))
    monkeypatch.setattr(activity, "wait_quiet", lambda *a, **k: None)
    text, cost, provider = b.code_text("ROLE: coder.", [{"role": "user", "content": "go"}])
    assert "x = 1" in text and cost == 0.0
